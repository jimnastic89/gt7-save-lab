const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const G=require('../web/core.js');
const root=path.resolve(__dirname,'../download_analysis');
const saves=[1,2,3].map(n=>G.parse(fs.readFileSync(path.join(root,String(n),'gt7save.bin'))));
assert.deepEqual(saves.map(s=>s.records.length),[38,38,38]);
assert.deepEqual(saves.map(s=>G.giftInfo(s).count),[59,68,77]);
assert.deepEqual(saves.map(s=>G.read(s,'PROGRESS',0x152,'u32','BE')),['11800','11800','11800']);
assert.deepEqual(saves.map(s=>G.read(s,'GARAGE',0x34,'u16','BE')),['3370','3356','3370']);
assert.deepEqual(G.changes(saves[0],saves[1]).map(x=>x.name),['GAMECTX','GMSTATS','GARAGE','GIFTIV']);
const edited=G.parse(saves[2].bytes.slice());
G.write(edited,'PROGRESS',0x152,'u32','BE','12000');
assert.equal(G.read(edited,'PROGRESS',0x152,'u32','BE'),'12000');
assert.equal(G.read(saves[2],'PROGRESS',0x152,'u32','BE'),'11800');
assert.deepEqual(G.changes(saves[2],edited).map(x=>x.name),['PROGRESS']);
assert.throws(()=>G.write(edited,'PROGRESS',0x152,'u32','BE','4294967296'));
assert.throws(()=>G.write(edited,'PROGRESS',0x152,'u32','BE','-1'));
assert.throws(()=>G.write(edited,'PROGRESS',0x152,'u32','BE','1.5'));
assert.throws(()=>G.write(edited,'PROGRESS',703,'u32','BE','1'));
assert.throws(()=>G.write(edited,'PROGRESS',0,'hex','BE','ABC'));
assert.throws(()=>G.parse(saves[0].bytes.slice(0,-1)));
const malformed=saves[0].bytes.slice();malformed.fill(255,12,16);assert.throws(()=>G.parse(malformed));
G.write(edited,'PROGRESS',0,'u64','BE','18446744073709551615');
assert.equal(G.read(edited,'PROGRESS',0,'u64','BE'),'18446744073709551615');
G.write(edited,'PROGRESS',0,'i64','LE','-9223372036854775808');
assert.equal(G.read(edited,'PROGRESS',0,'i64','LE'),'-9223372036854775808');
assert.throws(()=>G.write(edited,'PROGRESS',0,'f32','BE','1e100'));
assert.throws(()=>G.offsetValue('12oops'));
assert.equal(G.offsetValue('0x152'),338);
console.log('PASS: three real saves, gift structure, shifted records, integer/float bounds, exact 64-bit values, malformed data and edit isolation.');
const fourth=G.parse(fs.readFileSync(path.join(root,'4','gt7save.bin')));
assert.equal(G.read(fourth,'PROGRESS',0x152,'u32','BE'),'12400');
assert.equal(G.read(fourth,'GMSTATS',0x9a,'u64','BE'),'81575');
assert.equal(G.eventInfo(fourth).find(e=>e.id==='1000017').time,'17968');
const inventory=G.giftInfo(fourth);
assert.equal(inventory.count,86);
assert.deepEqual(inventory.entries.slice(-9).map(e=>e.details.ticket_.rouletteid_),[1,2,3,4,5,6,11,12,13]);
assert.equal(inventory.entries[77].id,'9079767022194209');
assert.equal(inventory.entries[77].details.itemId_,'9079767022194209');
const removed=G.removeGifts(fourth,[0,12,85]);
assert.equal(G.giftInfo(removed).count,83);
assert.equal(removed.bytes.length,fourth.bytes.length-3*450);
assert.deepEqual(G.changes(fourth,removed).map(c=>c.name),['GIFTIV']);
assert.deepEqual(G.giftInfo(removed).entries.map(e=>e.id),inventory.entries.filter(e=>![0,12,85].includes(e.index)).map(e=>e.id));
assert.equal(G.giftInfo(G.removeGifts(fourth,inventory.entries.map(e=>e.index))).count,0);
assert.throws(()=>G.removeGifts(fourth,[86]));
const changedCredits=G.parse(removed.bytes);G.write(changedCredits,'PROGRESS',0x152,'u32','BE','13000');assert.equal(G.read(changedCredits,'PROGRESS',0x152,'u32','BE'),'13000');
console.log('PASS: fourth-save fields, event-ID lookup, lossless ticket IDs, noncontiguous/empty gift removal, shifted credit edits.');
